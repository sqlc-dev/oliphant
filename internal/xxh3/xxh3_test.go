func TestOracleVectors(t *testing.T) {
	buf := make([]byte, 4096)
	for i := range buf {
		buf[i] = byte(i*7 + 1)
	}
	for _, v := range oracleVectors {
		if got := Hash64Seed(buf[:v.length], v.seed); got != v.expected {
			t.Errorf("Hash64Seed(buf[:%d], %d) = %d, want %d", v.length, v.seed, got, v.expected)
		}
	}
}

import "testing"

// The three vectors pg_query_go's TestHashXXH3_64 hard-codes
// (fingerprint_test.go, v6.2.2).
var pgQueryGoVectors = []struct {
	input    string
	seed     uint64
	expected uint64
}{
	{"TEST", 0, 11717748491247689214},
	{"TEST", 42, 10412276358662179996},
	{"Something else", 0, 14679351602596009561},
}

func TestPgQueryGoVectors(t *testing.T) {
	for _, v := range pgQueryGoVectors {
		if got := Hash64Seed([]byte(v.input), v.seed); got != v.expected {
			t.Errorf("Hash64Seed(%q, %d) = %d, want %d", v.input, v.seed, got, v.expected)
		}
	}
}

